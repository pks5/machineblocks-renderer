interface Placement {
  id: string;
  typeFqn: string;
  size: string;
  direction: string;
  offset: string;
}

/** MachineBlocks customizer palette, shared by baseColor and highlightColor. */
const COLOR_DROPDOWN =
  "[#58B99D:Turquoise, #4A9E86:Green Sea, #65C97A:Emerald, #55AB68:Nephritis, #5296D5:Peter River, #437EB4:Belize Hole, #925CB1:Amethyst, #8548A8:Wisteria, #38485C:Wet Asphalt, #303D4E:Midnight Blue, #EAC645:Sun Flower, #E7A03C:Orange, #D4813A:Carrot, #C05A23:Pumpkin, #D65745:Alizarin, #B14434:Pomegranate, #EDF0F1:Clouds, #BEC3C6:Silver, #98A4A6:Concrete, #98A4A6:Asbestos]";

type Registry = RenderContext["session"]["typeRegistry"];

export function renderSetFile(
  block: BlockDefinition,
  outputRelativePath: string,
  outputBasePath: string,
  mbLibPath: string,
  mapping: ManifestationMapping,
  registry: Registry,
  configSet: string | undefined,
): RenderOutput {
  const source = block.source ?? { file: "", line: 1, column: 1 };
  const placements: Placement[] = [];
  for (const child of compositionChildren(block, "parts")) {
    if (child.kind !== "blockInstance") {
      continue;
    }
    const placement = placementOf(child.instance, source, registry);
    if ("files" in placement) {
      return placement;
    }
    placements.push(placement);
  }
  const ordered = orderBySteps(block, placements);
  const root = mapManifestation(block.type, mapping, "selected");
  if (!root.ok) {
    return errorOutput(root.code, root.message, source);
  }
  const moduleName = moduleNameForManifestation(root.fqn);
  const filename = outputRelativePath.split("/").pop() ?? `${block.name}.scad`;
  const outputDir = dirnamePosix(joinPosix(outputBasePath, outputRelativePath));
  const typeManifestations = new Map<string, string>();
  for (const placement of ordered) {
    if (typeManifestations.has(placement.typeFqn)) {
      continue;
    }
    const manifested = mapManifestation(placement.typeFqn, mapping, "reference");
    if (!manifested.ok) {
      return errorOutput(manifested.code, manifested.message, source);
    }
    typeManifestations.set(placement.typeFqn, manifested.fqn);
  }
  const config = loadConfigPrelude(registry, configSet, outputRelativePath, outputBasePath, mbLibPath, mapping);
  if (!config.ok) {
    return config.output;
  }
  const imports = [
    `use <${relativePosix(outputDir, joinPosix(mbLibPath, "lib/block.scad"))}>;`,
    config.prelude.useLine,
    ...distinctTypeImports(ordered, outputDir, outputBasePath, typeManifestations),
  ];
  const instances = distinctById(ordered);
  const firstId = escapeScad(ordered[0]?.id ?? "00001");
  const baseColorValue = escapeScad(literalColor(block, "baseColor", "#EAC645"));
  const highlightColorValue = escapeScad(literalColor(block, "highlightColor", "#55AB68"));
  const stepMax = Math.max(ordered.length - 1, 0);
  const steps = ordered
    .map(
      (placement) =>
        `    ["${escapeScad(placement.id)}", ${placement.size}, ${placement.direction}, ${placement.offset}]`,
    )
    .join(",\n");
  const dispatch = instances
    .map((placement, index) => {
      const keyword = index === 0 ? "if" : "else if";
      return `        ${keyword} (instanceId == "${escapeScad(placement.id)}") ${moduleName}__Instance_${placement.id}(config = config, settings = settings);`;
    })
    .join("\n");
  const instanceModules = instances
    .map((placement) => instanceModule(moduleName, placement, typeManifestations))
    .join("\n\n");
  const viewId = escapeScad(block.type);
  const stepsLocal = generatedLocal("STEPS");
  const blockIdLocal = generatedLocal("blockId");
  const indexLocal = generatedLocal("i");

  const content = `/**
 * MachineBlocks.com Block File
 *
 * Name: ${block.name}
 * Filename: ${filename}
 * Package: ${block.type}
 * Generated by: machineblocks-render-target (${RENDER_TARGET_VERSION})
 */

/* Imports */
${imports.join("\n")}

/* Customization */
${config.prelude.dropdown}

mode = "total"; // [total:Total, print:3D Print, step:Step, instance:Instance]
step = 0; // [0:${stepMax}]
instanceId = "${firstId}";
baseColor = "${baseColorValue}"; // ${COLOR_DROPDOWN}
highlightColor = "${highlightColorValue}"; // ${COLOR_DROPDOWN}
assembly = "merged"; // [unassembled:Unassembled, assembled:Assembled, merged:Merged]

/* [Hidden] */
${config.prelude.hidden}
${stepsLocal} = [
${steps}
];

/* Main Module Call */
${moduleName}(
    config = ${hiddenCustomizer("config")},
    settings = [
        ["baseColor", baseColor],
        ["highlightColor", highlightColor],
        ["mode", mode],
        ["step", step],
        ["instanceId", instanceId],
        ["combined", true],
        ["assembly", assembly]
    ]
);

/* Main Module Definition */
module ${moduleName}(config = undef, settings = undef) {
    mode = mb_param(config, settings, "mode", default="total");

    if (mode == "total") ${moduleName}__Total(config = config, settings = settings);
    else if (mode == "print") ${moduleName}__Print(config = config, settings = settings);
    else if (mode == "step") ${moduleName}__Step(config = config, settings = settings);
    else if (mode == "instance") ${moduleName}__Instance(config = config, settings = settings);
}

/* Optional Sub Modules */
module ${moduleName}__Total(config = undef, settings = undef) {
    ${blockIdLocal} = mb_param_id(config, settings, "${viewId}.total");
    baseColor = mb_param_baseColor(config, settings);
    align = mb_param_align(config, settings);
    direction = mb_param_direction(config, settings);
    offset = mb_param_offset(config, settings);

    mb_block(
        config = config,
        settings = [
            ["id", ${blockIdLocal}],
            ["base", false],
            ["studs", false],
            ["align", align],
            ["offset", offset],
            ["direction", direction],
            ["size", mb_parts_total_size(${stepsLocal})]
        ]
    ) {
        for (${indexLocal} = [0 : len(${stepsLocal}) - 1]) {
            ${moduleName}__Instance(
                config = config,
                settings = [
                    ["id", mb_block_id(${blockIdLocal}, ${stepsLocal}[${indexLocal}][0])],
                    ["instanceId", ${stepsLocal}[${indexLocal}][0]],
                    ["size", ${stepsLocal}[${indexLocal}][1]],
                    ["direction", ${stepsLocal}[${indexLocal}][2]],
                    ["offset", ${stepsLocal}[${indexLocal}][3]],
                    ["baseColor", baseColor],
                    ["assembly", "merged"]
                ]
            );
        }
    }
}

module ${moduleName}__Print(config = undef, settings = undef) {
    ${blockIdLocal} = mb_param_id(config, settings, "${viewId}.print");
    baseColor = mb_param_baseColor(config, settings);
    align = mb_param_align(config, settings);
    direction = mb_param_direction(config, settings);
    offset = mb_param_offset(config, settings);
    assembly = mb_param_assembly(config, settings);

    mb_block(
        config = config,
        settings = [
            ["id", ${blockIdLocal}],
            ["base", false],
            ["studs", false],
            ["align", align],
            ["offset", offset],
            ["direction", direction],
            ["size", mb_parts_total_size(${stepsLocal})]
        ]
    ) {
        for (${indexLocal} = [0 : len(${stepsLocal}) - 1]) {
            ${moduleName}__Instance(
                config = config,
                settings = [
                    ["id", mb_block_id(${blockIdLocal}, ${stepsLocal}[${indexLocal}][0])],
                    ["instanceId", ${stepsLocal}[${indexLocal}][0]],
                    ["size", ${stepsLocal}[${indexLocal}][1]],
                    ["offset", mb_set_step_print_position(assembly, ${stepsLocal}, ${indexLocal})],
                    ["assembly", assembly],
                    ["baseColor", baseColor]
                ]
            );
        }
    }
}

module ${moduleName}__Step(config = undef, settings = undef) {
    ${blockIdLocal} = mb_param_id(config, settings, "${viewId}.step");
    step = mb_param(config, settings, "step");
    combined = mb_param(config, settings, "combined", false);
    highlightColor = mb_param(config, settings, "highlightColor", "#EAC645");
    baseColor = mb_param_baseColor(config, settings);
    align = mb_param_align(config, settings);
    direction = mb_param_direction(config, settings);
    offset = mb_param_offset(config, settings);
    instanceId = step < len(${stepsLocal}) ? ${stepsLocal}[step][0] : undef;

    if (instanceId != undef) {
        mb_block(
            config = config,
            settings = [
                ["id", ${blockIdLocal}],
                ["base", false],
                ["studs", false],
                ["align", align],
                ["offset", offset],
                ["direction", direction],
                ["size", mb_parts_total_size(${stepsLocal})]
            ]
        ) {
            if (combined) {
                for (${indexLocal} = [0 : step - 1]) {
                    ${moduleName}__Instance(
                        config = config,
                        settings = [
                            ["id", mb_block_id(${blockIdLocal}, ${stepsLocal}[${indexLocal}][0])],
                            ["instanceId", ${stepsLocal}[${indexLocal}][0]],
                            ["size", ${stepsLocal}[${indexLocal}][1]],
                            ["direction", ${stepsLocal}[${indexLocal}][2]],
                            ["offset", ${stepsLocal}[${indexLocal}][3]],
                            ["baseColor", baseColor],
                            ["assembly", "merged"]
                        ]
                    );
                }
            }
            ${moduleName}__Instance(
                config = config,
                settings = [
                    ["id", mb_block_id(${blockIdLocal}, instanceId)],
                    ["instanceId", instanceId],
                    ["size", ${stepsLocal}[step][1]],
                    ["direction", ${stepsLocal}[step][2]],
                    ["offset", ${stepsLocal}[step][3]],
                    ["baseColor", combined ? highlightColor : baseColor],
                    ["assembly", "merged"]
                ]
            );
        }
    }
}

module ${moduleName}__Instance(config = undef, settings = undef) {
    instanceId = mb_param(config, settings, "instanceId");

    if (instanceId != undef) {
${dispatch}
    }
}

${instanceModules}

/* Optional Helper Modules */
/* Optional Global Functions */
`;

  return { files: [withSourceMap(block, { path: outputRelativePath, content })] };
}

function instanceModule(
  moduleName: string,
  placement: Placement,
  typeManifestations: ReadonlyMap<string, string>,
): string {
  const part = moduleNameForManifestation(manifestedType(placement.typeFqn, typeManifestations));
  const blockIdLocal = generatedLocal("blockId");
  return `module ${moduleName}__Instance_${placement.id}(config = undef, settings = undef) {
    ${blockIdLocal} = mb_param_id(config, settings);
    baseColor = mb_param_baseColor(config, settings);
    assembly = mb_param_assembly(config, settings);
    size = mb_param_size(config, settings);
    direction = mb_param_direction(config, settings);
    offset = mb_param_offset(config, settings);

    ${part}(
        config = config,
        settings = [
            ["id", ${blockIdLocal}],
            ["size", size],
            ["direction", direction],
            ["offset", offset],
            ["baseColor", baseColor],
            ["assembly", assembly]
        ]
    );
}`;
}

function distinctById(placements: readonly Placement[]): Placement[] {
  const seen = new Set<string>();
  const instances: Placement[] = [];
  for (const placement of placements) {
    if (seen.has(placement.id)) {
      continue;
    }
    seen.add(placement.id);
    instances.push(placement);
  }
  return instances;
}

function literalColor(block: BlockDefinition, name: string, fallback: string): string {
  const property = block.members.find((member) => member.kind === "property" && member.name === name);
  if (
    property &&
    property.kind === "property" &&
    property.value?.kind === "literal" &&
    typeof property.value.value === "string"
  ) {
    return property.value.value;
  }
  return fallback;
}

function escapeScad(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function placementOf(
  instance: BlockInstance,
  source: { file: string; line: number; column: number },
  registry: Registry,
): Placement | RenderOutput {
  const id = literalString(instance.id);
  const size = memberScad(instance, "size", registry);
  if (!id || !size) {
    return errorOutput(SET_PART_INCOMPLETE, "A placed part needs an id and a size.", instance.source ?? source);
  }
  const direction = memberScad(instance, "direction", registry) ?? '"west"';
  const offset = memberScad(instance, "offset", registry) ?? "[0, 0, 0]";
  return { id, typeFqn: instance.typeFqn, size, direction, offset };
}

function memberScad(instance: BlockInstance, name: string, registry: Registry): string | undefined {
  const property = propertyOn(instance.typeFqn, name, registry);
  const member = instance.memberValues[name] ?? property?.value;
  if (!member) {
    return undefined;
  }
  if (member.kind === "literal") {
    return serializeLiteral(member, {
      registry,
      typeFqn: property?.typeFqn || member.typeFqn,
      type: property?.type,
    });
  }
  if (member.kind !== "expression") {
    return undefined;
  }
  const parsed = parseExpression(member.raw);
  if (!parsed.ok) {
    return undefined;
  }
  try {
    const value = evaluateExpression(parsed.result.ast, bindingScope(instance, registry));
    const outcome = serializeTyped(value, {
      registry,
      typeFqn: property?.typeFqn,
      type: property?.type,
    });
    return outcome.ok ? outcome.scad : undefined;
  } catch {
    return undefined;
  }
}

function bindingScope(instance: BlockInstance, registry: Registry): ExpressionScope {
  const cache = new Map<string, unknown>();
  const pending = new Set<string>();
  const scope: ExpressionScope = new Proxy({} as ExpressionScope, {
    has(_target, key) {
      return typeof key === "string" && read(key) !== undefined;
    },
    get(_target, key) {
      return typeof key === "string" ? read(key) : undefined;
    },
  });

  function read(name: string): unknown {
    if (cache.has(name)) {
      return cache.get(name);
    }
    if (pending.has(name)) {
      return undefined;
    }
    const property = propertyOn(instance.typeFqn, name, registry);
    const member = instance.memberValues[name] ?? property?.value;
    if (!member) {
      return undefined;
    }
    pending.add(name);
    let value: unknown;
    if (member.kind === "literal") {
      value = member.value;
    } else if (member.kind === "expression") {
      const parsed = parseExpression(member.raw);
      if (parsed.ok) {
        try {
          value = evaluateExpression(parsed.result.ast, scope);
        } catch {
          value = undefined;
        }
      }
    }
    pending.delete(name);
    if (value !== undefined) {
      cache.set(name, value);
    }
    return value;
  }

  return scope;
}

function propertyOn(typeFqn: string, name: string, registry: Registry): PropertyDefinition | undefined {
  const definition = registry.get(typeFqn)?.block;
  if (!definition) {
    return undefined;
  }
  const property = resolveEffectiveMembers(definition, registry).find(
    (member) => member.kind === "property" && member.name === name,
  );
  return property?.kind === "property" ? property : undefined;
}

function orderBySteps(block: BlockDefinition, placements: readonly Placement[]): Placement[] {
  const steps = compositionChildren(block, "steps").flatMap((child) => {
    if (child.kind !== "blockInstance") {
      return [];
    }
    const part = literalString(child.instance.memberValues.part) ?? literalString(child.instance.id);
    return part ? [part] : [];
  });
  if (steps.length === 0) {
    return [...placements];
  }
  const byId = new Map(placements.map((placement) => [placement.id, placement]));
  const ordered: Placement[] = [];
  for (const id of steps) {
    const placement = byId.get(id);
    if (placement) {
      ordered.push(placement);
    }
  }
  for (const placement of placements) {
    if (!ordered.includes(placement)) {
      ordered.push(placement);
    }
  }
  return ordered;
}

function manifestedType(typeFqn: string, typeManifestations: ReadonlyMap<string, string>): string {
  const manifestation = typeManifestations.get(typeFqn);
  if (!manifestation) {
    throw new Error(`Missing manifestation for ${typeFqn}`);
  }
  return manifestation;
}

function distinctTypeImports(
  placements: readonly Placement[],
  outputDir: string,
  outputBasePath: string,
  typeManifestations: ReadonlyMap<string, string>,
): string[] {
  const seen = new Set<string>();
  const lines: string[] = [];
  for (const placement of placements) {
    if (seen.has(placement.typeFqn)) {
      continue;
    }
    seen.add(placement.typeFqn);
    const manifestation = typeManifestations.get(placement.typeFqn);
    if (!manifestation) {
      continue;
    }
    const target = joinPosix(outputBasePath, pathForManifestation(manifestation, "scad"));
    lines.push(`use <${relativePosix(outputDir, target)}>;`);
  }
  return lines;
}

function literalString(value: LiteralValue | BlockInstance["id"] | BlockInstance["memberValues"][string] | undefined): string | undefined {
  if (!value || value.kind !== "literal" || typeof value.value !== "string") {
    return undefined;
  }
  return value.value;
}
