import type { BlockDefinition, BlockInstance, LiteralValue, PropertyDefinition } from "@blockml/bom";
import type { RenderContext, RenderOutput } from "@blockml/compiler";
import { resolveEffectiveMembers } from "@blockml/framework";
import { compositionChildren } from "./composition.js";
import { SET_PART_INCOMPLETE, errorOutput } from "./diagnostics.js";
import { dirnamePosix, joinPosix, relativePosix } from "./paths.js";
import { mapManifestation, moduleNameForManifestation, pathForManifestation, type ManifestationMapping } from "./naming.js";
import { serializeLiteral } from "./serialize.js";
import { withSourceMap } from "./source-map.js";
import { RENDER_TARGET_VERSION } from "./version.js";

interface Placement {
  id: string;
  typeFqn: string;
  size: string;
  direction: string;
  offset: string;
}

type Registry = RenderContext["session"]["typeRegistry"];

export function renderSetFile(
  block: BlockDefinition,
  outputRelativePath: string,
  outputBasePath: string,
  mbLibPath: string,
  mapping: ManifestationMapping,
  registry: Registry,
): RenderOutput {
  const source = block.source ?? { file: "", line: 1, column: 1 };
  const placements: Placement[] = [];
  for (const child of compositionChildren(block, "parts")) {
    if (child.kind !== "blockInstance") {
      continue;
    }
    const placement = placementOf(child.instance, source, registry);
    if ("files" in placement) {
      return placement;
    }
    placements.push(placement);
  }
  const ordered = orderBySteps(block, placements);
  const root = mapManifestation(block.type, mapping, "selected");
  if (!root.ok) {
    return errorOutput(root.code, root.message, source);
  }
  const moduleName = moduleNameForManifestation(root.fqn);
  const filename = outputRelativePath.split("/").pop() ?? `${block.name}.scad`;
  const outputDir = dirnamePosix(joinPosix(outputBasePath, outputRelativePath));
  const typeManifestations = new Map<string, string>();
  for (const placement of ordered) {
    if (typeManifestations.has(placement.typeFqn)) {
      continue;
    }
    const manifested = mapManifestation(placement.typeFqn, mapping, "reference");
    if (!manifested.ok) {
      return errorOutput(manifested.code, manifested.message, source);
    }
    typeManifestations.set(placement.typeFqn, manifested.fqn);
  }
  const imports = [
    `use <${relativePosix(outputDir, joinPosix(mbLibPath, "lib/block.scad"))}>;`,
    `include <${relativePosix(outputDir, joinPosix(mbLibPath, "config/mb_config.scad"))}>;`,
    ...distinctTypeImports(ordered, outputDir, outputBasePath, typeManifestations),
  ];
  const firstId = ordered[0]?.id ?? "00001";
  const baseColor = block.members.find((member) => member.kind === "property" && member.name === "baseColor");
  const baseColorValue =
    baseColor && baseColor.kind === "property" && baseColor.value?.kind === "literal" && typeof baseColor.value.value === "string"
      ? baseColor.value.value
      : "#EAC645";
  const steps = ordered
    .map((placement) => `        ["${placement.id}", ${placement.size}, ${placement.direction}, ${placement.offset}]`)
    .join(",\n");
  const instanceCalls = ordered.map((placement) => `    ${moduleName}__Instance_${placement.id}();`).join("\n");
  const stepCalls = ordered
    .map((placement, index) => `    if (step >= ${index}) ${moduleName}__Instance_${placement.id}();`)
    .join("\n");
  const dispatch = ordered
    .map((placement, index) => {
      const keyword = index === 0 ? "if" : "else if";
      return `    ${keyword} (instanceId == "${placement.id}") ${moduleName}__Instance_${placement.id}();`;
    })
    .join("\n");
  const instanceModules = ordered
    .map(
      (placement) => `module ${moduleName}__Instance_${placement.id}() {
    ${moduleNameForManifestation(manifestedType(placement.typeFqn, typeManifestations))}(
        config = mb_config,
        settings = [
            ["size", ${placement.size}],
            ["offset", ${placement.offset}],
            ["direction", ${placement.direction}]
        ]
    );
}`,
    )
    .join("\n\n");

  const content = `/**
 * MachineBlocks.com Block File
 *
 * Name: ${block.name}
 * Filename: ${filename}
 * Package: ${block.type}
 * Generated by: machineblocks-render-target (${RENDER_TARGET_VERSION})
 */

/* Imports */
${imports.join("\n")}

/* Customization */
mode = "total"; // [total:Total, print:3D Print, step:Step, instance:Instance]
step = 0; // [0:9]
instanceId = "${firstId}";
assembly = "merged"; // [unassembled:Unassembled, assembled:Assembled, merged:Merged]
baseColor = "${baseColorValue}";

/* Main Module Call */
${moduleName}(config = mb_config);

/* Main Module Definition */
module ${moduleName}(config = undef) {
    STEPS = [
${steps}
    ];
    mb_block(
        config = config,
        settings = [
            ["size", mb_parts_total_size(STEPS)]
        ]
    );
    if (mode == "total") ${moduleName}__Total();
    else if (mode == "print") ${moduleName}__Print();
    else if (mode == "step") ${moduleName}__Step();
    else if (mode == "instance") ${moduleName}__Instance();
}

/* Optional Sub Modules */
module ${moduleName}__Total() {
${instanceCalls}
}

module ${moduleName}__Print() {
${instanceCalls}
}

module ${moduleName}__Step() {
${stepCalls}
}

module ${moduleName}__Instance() {
${dispatch}
}

${instanceModules}

/* Optional Helper Modules */
/* Optional Global Functions */
`;

  return { files: [withSourceMap(block, { path: outputRelativePath, content })] };
}

function placementOf(
  instance: BlockInstance,
  source: { file: string; line: number; column: number },
  registry: Registry,
): Placement | RenderOutput {
  const id = literalString(instance.id);
  const size = placedValue(instance, "size", registry) ?? typeDefault(instance.typeFqn, "size", registry);
  if (!id || !size) {
    return errorOutput(SET_PART_INCOMPLETE, "A placed part needs an id and a size.", instance.source ?? source);
  }
  const direction = placedValue(instance, "direction", registry) ?? '"west"';
  const offset = placedValue(instance, "offset", registry) ?? "[0, 0, 0]";
  return { id, typeFqn: instance.typeFqn, size, direction, offset };
}

function placedValue(instance: BlockInstance, name: string, registry: Registry): string | undefined {
  const member = instance.memberValues[name];
  if (!member || member.kind !== "literal") {
    return undefined;
  }
  const property = propertyOn(instance.typeFqn, name, registry);
  return serializeLiteral(member, {
    registry,
    typeFqn: property?.typeFqn || member.typeFqn,
    type: property?.type,
  });
}

function typeDefault(typeFqn: string, name: string, registry: Registry): string | undefined {
  const property = propertyOn(typeFqn, name, registry);
  if (!property?.value || property.value.kind !== "literal") {
    return undefined;
  }
  return serializeLiteral(property.value, { registry, typeFqn: property.typeFqn, type: property.type });
}

function propertyOn(typeFqn: string, name: string, registry: Registry): PropertyDefinition | undefined {
  const definition = registry.get(typeFqn)?.block;
  if (!definition) {
    return undefined;
  }
  const property = resolveEffectiveMembers(definition, registry).find(
    (member) => member.kind === "property" && member.name === name,
  );
  return property?.kind === "property" ? property : undefined;
}

function orderBySteps(block: BlockDefinition, placements: readonly Placement[]): Placement[] {
  const steps = compositionChildren(block, "steps").flatMap((child) => {
    if (child.kind !== "blockInstance") {
      return [];
    }
    const part = literalString(child.instance.memberValues.part) ?? literalString(child.instance.id);
    return part ? [part] : [];
  });
  if (steps.length === 0) {
    return [...placements];
  }
  const byId = new Map(placements.map((placement) => [placement.id, placement]));
  const ordered: Placement[] = [];
  for (const id of steps) {
    const placement = byId.get(id);
    if (placement) {
      ordered.push(placement);
    }
  }
  for (const placement of placements) {
    if (!ordered.includes(placement)) {
      ordered.push(placement);
    }
  }
  return ordered;
}

function manifestedType(typeFqn: string, typeManifestations: ReadonlyMap<string, string>): string {
  const manifestation = typeManifestations.get(typeFqn);
  if (!manifestation) {
    throw new Error(`Missing manifestation for ${typeFqn}`);
  }
  return manifestation;
}

function distinctTypeImports(
  placements: readonly Placement[],
  outputDir: string,
  outputBasePath: string,
  typeManifestations: ReadonlyMap<string, string>,
): string[] {
  const seen = new Set<string>();
  const lines: string[] = [];
  for (const placement of placements) {
    if (seen.has(placement.typeFqn)) {
      continue;
    }
    seen.add(placement.typeFqn);
    const manifestation = typeManifestations.get(placement.typeFqn);
    if (!manifestation) {
      continue;
    }
    const target = joinPosix(outputBasePath, pathForManifestation(manifestation, "scad"));
    lines.push(`use <${relativePosix(outputDir, target)}>;`);
  }
  return lines;
}

function literalString(value: LiteralValue | BlockInstance["id"] | BlockInstance["memberValues"][string] | undefined): string | undefined {
  if (!value || value.kind !== "literal" || typeof value.value !== "string") {
    return undefined;
  }
  return value.value;
}
