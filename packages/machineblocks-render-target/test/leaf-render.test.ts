import { describe, expect, it } from "vitest";
import { parse } from "@blockml/parser";
import { TypeRegistry } from "@blockml/framework";
import { buildRenderSession, createRenderContext } from "@blockml/compiler";
import type { BomDocument, LiteralValue } from "@blockml/bom";
import { BlockRenderEngine } from "@blockml/block-render-engine";
import {
  MachineBlocksRenderTarget,
  scadModuleName,
  scadOutputPath,
  serializeLiteral,
} from "@machineblocks/render-target";

const LIB = {
  "machineblocks-v3-scad": { mbLibPath: "/mb" },
};

const FIXTURE = `<?xml version="1.0"?>
<bricks:Fixture xmlns="http://blockml.org/bml"
  xmlns:type="org.blockml.bml.type"
  xmlns:bricks="com.machineblocks.bml.bricks"
  xmlns:mbcore="com.machineblocks.bml.core">
  <baseType>mbcore:Block</baseType>
  <is>A leaf fixture</is>
  <properties>
    <studs type="type:Boolean"><value>true</value></studs>
    <grilleCount type="type:Integer"><value>5</value></grilleCount>
  </properties>
  <aggregations>
    <_parts override="true">
      <composition>
        <mbcore:NativeBlock studs="\${ studs }" grilleCount="\${ grilleCount }" />
      </composition>
    </_parts>
  </aggregations>
</bricks:Fixture>
`;

function document(source: string, filePath: string): BomDocument {
  const parsed = parse(source, { filePath });
  if (!parsed.document) {
    throw new Error(parsed.diagnostics.map((diagnostic) => diagnostic.message).join("\n"));
  }
  return parsed.document;
}

function render(source: string, filePath: string, targetOptions: unknown = LIB, extras: BomDocument[] = []) {
  const registry = new TypeRegistry();
  for (const extra of extras) {
    registry.register(extra);
  }
  registry.register(document(source, filePath));
  const session = buildRenderSession({
    typeRegistry: registry,
    targetName: "machineblocks-v3-scad",
    scopeKind: "document",
    sourceFilePath: filePath,
    outputBasePath: "/out",
  });
  const target = new MachineBlocksRenderTarget(new BlockRenderEngine());
  return target.render({ scope: { kind: "document" }, targetOptions }, createRenderContext(session));
}

describe("MachineBlocksRenderTarget leaf slice", () => {
  it("names Standard without rendering it", () => {
    expect(scadModuleName("com.machineblocks.bml.bricks.Standard")).toBe(
      "mb__com__machineblocks__scad__bricks__Standard",
    );
    expect(scadOutputPath("com.machineblocks.bml.bricks.Standard")).toBe(
      "com/machineblocks/scad/bricks/Standard.scad",
    );
  });

  it("emits a module and a main call for one NativeBlock child", () => {
    const result = render(FIXTURE, "fixture.bml");

    expect(result.diagnostics ?? []).toEqual([]);
    const file = result.files[0];
    expect(file?.path).toBe("com/machineblocks/scad/bricks/Fixture.scad");
    expect(file?.content).toBe(`/**
 * MachineBlocks.com Block File
 *
 * Name: Fixture
 * Filename: Fixture.scad
 * Package: com.machineblocks.bml.bricks.Fixture
 * Generated by: machineblocks-render-target (0.1.0)
 */

/* Imports */
use <../../../../../mb/lib/block.scad>;
include <../../../../../mb/config/mb_config.scad>;

/* Customization */
studs = true;
grilleCount = 5;

/* Main Module Call */
mb__com__machineblocks__scad__bricks__Fixture(
    config = mb_config,
    settings = [
        ["studs", studs],
        ["grilleCount", grilleCount]
    ]
);

/* Main Module Definition */
module mb__com__machineblocks__scad__bricks__Fixture(config = undef, settings = undef) {
    studs = mb_param(config, settings, "studs", true);
    grilleCount = mb_param(config, settings, "grilleCount", 5);
    size = mb_param_size(config, settings);
    align = mb_param_align(config, settings);
    offset = mb_param_offset(config, settings);
    direction = mb_param_direction(config, settings);
    mb_block(
        config = config,
        settings = [
            ["studs", studs],
            ["grilleCount", grilleCount],
            ["size", size],
            ["align", align],
            ["offset", offset],
            ["direction", direction]
        ]
    );
}

/* Optional Sub Modules */
/* Optional Helper Modules */
/* Optional Global Functions */
`);
    const map = JSON.parse((file as { sourceMap?: string }).sourceMap ?? "{}") as { version?: number; sources?: string[] };
    expect(map.version).toBe(3);
    expect(map.sources).toContain("fixture.bml");
  });

  it("serializes string and SizeXYZ literals", () => {
    const text: LiteralValue = {
      kind: "literal",
      value: 'say "hi"',
      typeFqn: "org.blockml.bml.type.Text",
    };
    const size: LiteralValue = {
      kind: "literal",
      value: { x: 4, y: 2, z: 3 },
      typeFqn: "com.machineblocks.bml.type.SizeXYZ",
    };
    expect(serializeLiteral(text)).toBe('"say \\"hi\\""');
    expect(serializeLiteral(size)).toBe("[4, 2, 3]");
  });

  it("rejects object settings without a file", () => {
    const result = render(FIXTURE, "fixture.bml", {
      "machineblocks-v3-scad": { mbLibPath: "/mb", settingsFormat: "object" },
    });
    expect(result.files).toEqual([]);
    expect(result.diagnostics?.map((diagnostic) => diagnostic.code)).toEqual([
      "BML_SETTINGS_FORMAT_UNSUPPORTED",
    ]);
  });

  it("sends a Set to the set processor", () => {
    const block = document(
      `<mbcore:Block xmlns="http://blockml.org/bml" xmlns:mbcore="com.machineblocks.bml.core"><is>Block</is></mbcore:Block>`,
      "block.bml",
    );
    const set = document(
      `<mbcore:Set xmlns="http://blockml.org/bml" xmlns:mbcore="com.machineblocks.bml.core"><baseType>mbcore:Block</baseType><is>Set</is></mbcore:Set>`,
      "set.bml",
    );
    const result = render(
      `<sets:Kit xmlns="http://blockml.org/bml" xmlns:sets="com.example.bml.sets" xmlns:mbcore="com.machineblocks.bml.core"><baseType>mbcore:Set</baseType><is>A set</is></sets:Kit>`,
      "kit.bml",
      LIB,
      [block, set],
    );
    expect(result.diagnostics ?? []).toEqual([]);
    const content = result.files[0]?.content ?? "";
    expect(content).toContain("STEPS = [");
    expect(content).toContain("module mb__com__example__scad__sets__Kit__Total()");
    expect(content).toContain("module mb__com__example__scad__sets__Kit__Print()");
    expect(content).toContain("module mb__com__example__scad__sets__Kit__Step()");
    expect(content).toContain("module mb__com__example__scad__sets__Kit__Instance()");
    expect(content).toContain("mb_set_bounding_box(STEPS)");
  });

  it("reports BML_NO_TARGET when the chain has no Block", () => {
    const result = render(
      `<notes:Note xmlns="http://blockml.org/bml" xmlns:notes="org.example.notes"><baseType>org.example.Thing</baseType><is>A note</is></notes:Note>`,
      "note.bml",
    );
    expect(result.files).toEqual([]);
    expect(result.diagnostics?.map((diagnostic) => diagnostic.code)).toEqual(["BML_NO_TARGET"]);
  });
});
